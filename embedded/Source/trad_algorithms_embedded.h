/**
 * trad_algorithms_embedded.h
 *
 * Embedded-friendly (no STL, no dynamic memory) streaming implementations
 * of four traditional online trajectory compression algorithms:
 *
 *   1. OPWTR   — Online Piece-Wise Time-Ratio (SED-based)
 *   2. Dead Reckoning (DR) — angular deviation accumulation
 *   3. SQUISH-E (fixed window) — priority-queue simplified to fixed ring buffer
 *   4. VOLTCom  — Vector-based online compression (linear interpolation)
 *
 * Design constraints (same as acost_embedded.h):
 *   - Fixed-size arrays only; no new/delete, no std::vector.
 *   - All coordinates in decimal degrees; timestamps in milliseconds.
 *   - Each algorithm exposes a feed() call that returns true when it decides
 *     to emit a key-point (i.e., a compressed "output" for this position).
 *     The caller times the gap between feed() and the paired decompress()
 *     to measure end-to-end latency per GPS sample.
 *
 * End-to-end timing model for window-based algorithms:
 *   - A "result" (decoded point) is produced every time the algorithm emits
 *     a key-point.  Between two emissions multiple input points accumulate in
 *     the window with zero output; those points are considered to have the
 *     same E2E cost spread equally over the window, so per-sample E2E =
 *     (compress_window_time + decompress_one_point_time) / window_points.
 *   - For pure streaming algorithms (OPWTR, DR, VOLTCom) every input point
 *     produces an immediate decision: cost is measured per point directly.
 */

#pragma once

#include <cstdint>
#include <cmath>
#include <cstring>

#ifndef M_PI
#define M_PI 3.14159265358979323846
#endif

static constexpr double kDegToRad_trad = M_PI / 180.0;

// ?????????????????????????????????????????????????????????????????????????????
//  Shared: simple GPS point
// ?????????????????????????????????????????????????????????????????????????????

struct TradPoint {
    double   lon;      ///< decimal degrees
    double   lat;      ///< decimal degrees
    uint64_t ts;       ///< GPS timestamp, milliseconds
    uint32_t t_arrive; ///< DWT->CYCCNT when this point arrived (for E2E timing)
};

// ?????????????????????????????????????????????????????????????????????????????
//  Shared math helpers (inline so no separate .cpp needed)
// ?????????????????????????????????????????????????????????????????????????????

/** Squared Euclidean Distance in degree-space (fast, used for SED). */
static inline double sed_deg2(const TradPoint &a, const TradPoint &b,
                               const TradPoint &q) {
    // Linear interpolation of a?b at time q.ts
    double dt_ab = static_cast<double>(
        static_cast<int64_t>(b.ts) - static_cast<int64_t>(a.ts));
    if (dt_ab <= 0.0) return 0.0;
    double t = static_cast<double>(
        static_cast<int64_t>(q.ts) - static_cast<int64_t>(a.ts)) / dt_ab;
    double est_lon = a.lon + t * (b.lon - a.lon);
    double est_lat = a.lat + t * (b.lat - a.lat);
    double dlon = q.lon - est_lon;
    double dlat = q.lat - est_lat;
    return dlon * dlon + dlat * dlat;   // degree²
}

/** Haversine distance in metres. */
static inline double haversine_m(double lat1, double lon1,
                                  double lat2, double lon2) {
    const double R = 6371000.0;
    double dlat = (lat2 - lat1) * kDegToRad_trad;
    double dlon = (lon2 - lon1) * kDegToRad_trad;
    double la1  = lat1 * kDegToRad_trad;
    double la2  = lat2 * kDegToRad_trad;
    double a = std::sin(dlat / 2) * std::sin(dlat / 2)
             + std::cos(la1) * std::cos(la2)
             * std::sin(dlon / 2) * std::sin(dlon / 2);
    return R * 2.0 * std::atan2(std::sqrt(a), std::sqrt(1.0 - a));
}

// ?????????????????????????????????????????????????????????????????????????????
//  1. OPWTR  (Online Piece-Wise Time-Ratio, SED-based)
//
//  Streaming: processes one point at a time.
//  Keeps a sliding window [anchor .. candidate_end].
//  Emits anchor when any intermediate point exceeds SED(anchor, end, pt) > ?.
//  epsilon in degrees (1e-5 deg ? 1 m).
// ?????????????????????????????????????????????????????????????????????????????

/** Maximum number of points held in the OPWTR look-ahead window. */
#define OPWTR_WINDOW  8

struct OpwtrState {
    double   epsilon;
    TradPoint win[OPWTR_WINDOW];  ///< sliding window (circular)
    int       win_start;          ///< index of anchor (oldest)
    int       win_count;          ///< number of valid entries

    /** Last emitted key-point (used for decompression / E2E timing). */
    TradPoint last_key;
    bool      has_key;

    void init(double eps);

    /**
     * Feed one point.
     * @return true  — a key-point was emitted; decompress last_key.
     *         false — point absorbed into window, no output yet.
     */
    bool feed(const TradPoint &pt);

    /** Flush remaining window at end of trajectory (call once). */
    bool flush();
};

// ?????????????????????????????????????????????????????????????????????????????
//  2. Dead Reckoning (DR)
//
//  Streaming: tracks accumulated lateral deviation.
//  Emits when |sum(dist_i * sin(angle_i - angle_start))| > epsilon (metres).
// ?????????????????????????????????????????????????????????????????????????????

struct DrState {
    double   epsilon;     ///< metres
    TradPoint prev;       ///< previous point
    double   anchor_angle;///< heading at last emitted segment start
    double   accum;       ///< accumulated lateral deviation (metres)
    bool     started;

    TradPoint last_key;
    bool      has_key;

    void init(double eps_m);
    bool feed(const TradPoint &pt);
    bool flush();
};

// ?????????????????????????????????????????????????????????????????????????????
//  3. SQUISH-E (fixed-window streaming variant)
//
//  Maintains a fixed-size priority buffer (min-heap by SED priority).
//  When buffer is full, evicts the point with smallest SED contribution.
//  Emits the evicted point as the "compressed" key-point.
//  epsilon used as SED threshold for eviction decision.
// ?????????????????????????????????????????????????????????????????????????????

#define SQUISHE_BUF  16  ///< fixed buffer capacity (determines compression ratio)

struct SquisheEntry {
    TradPoint pt;
    double    priority;   ///< SED contribution (higher = more important)
    bool      valid;
};

struct SquisheState {
    double        epsilon;
    SquisheEntry  buf[SQUISHE_BUF];
    int           count;     ///< current number of valid entries

    TradPoint last_key;
    bool      has_key;

    void init(double eps);

    /**
     * Feed one point.
     * Returns true and sets last_key if a point was evicted from the buffer.
     */
    bool feed(const TradPoint &pt);

    /** Flush all remaining buffer entries at end of trajectory. */
    bool flush(TradPoint &out);

private:
    void recalc_priorities();
    int  find_min_priority_idx() const;
};

// ?????????????????????????????????????????????????????????????????????????????
//  4. VOLTCom (Vector-based Online Compression)
//
//  Streaming: maintains current vector (line segment a?b).
//  When Haversine error of new point against current vector exceeds epsilon,
//  closes the current vector (emits a key-point = segment end) and starts new.
//  epsilon in metres.
// ?????????????????????????????????????????????????????????????????????????????

struct VoltcomState {
    double   epsilon;     ///< metres
    TradPoint seg_start;  ///< start of current vector
    TradPoint seg_end;    ///< most recent extended endpoint
    bool      has_seg;

    TradPoint last_key;
    bool      has_key;

    void init(double eps_m);
    bool feed(const TradPoint &pt);
    bool flush();

    /** Decompress: reconstruct position at time ts from last emitted segment. */
    TradPoint decompress_at(uint64_t ts) const;
};
